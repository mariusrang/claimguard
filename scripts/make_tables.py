"""Turn the JSON files of results/ into markdown tables (results/tables.md) for the report.

    python scripts/make_tables.py --results results

It only prints what exists, so it can be run at any time during the project.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from claimguard.utils import load_json


def ci(m: dict) -> str:
    """Format a bootstrap result as '0.812 [0.770, 0.851]'."""
    return f"{m['value']:.3f} [{m['low']:.3f}, {m['high']:.3f}]"


def table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def pipeline_row(name: str, m: dict) -> list[str]:
    return [name, ci(m["accuracy"]), ci(m["macro_f1"]), f"{m['fever_score']:.3f}", f"{m['evidence_sentences']['f1']:.3f}"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default="results")
    args = parser.parse_args()
    res = Path(args.results)
    parts: list[str] = ["# Result tables (generated by scripts/make_tables.py)"]
    head = ["System", "Accuracy [95% CI]", "Macro-F1 [95% CI]", "FEVER score", "Evidence F1"]

    if (res / "retrieval.json").exists():
        r = load_json(res / "retrieval.json")
        rows = [
            [name, f"{m['recall@1']:.3f}", f"{m['recall@5']:.3f}", f"{m['recall@20']:.3f}", f"{m['precision@5']:.3f}", f"{m['mrr']:.3f}"]
            for name, m in r["systems"].items()
        ]
        parts += [f"## A1/A2 Retrieval (n={r['n_claims']} claims with evidence)",
                  table(["Retriever", "R@1", "R@5", "R@20", "P@5", "MRR"], rows)]
        tests = [[name, f"{t['mean_diff']:+.3f}", f"{t['p_value']:.4f}"] for name, t in r["vs_bm25_recall@5"].items()]
        if tests:
            parts += ["Paired permutation test on recall@5, against BM25:",
                      table(["System", "Mean difference", "p-value"], tests)]

    if (res / "baselines.json").exists():
        b = load_json(res / "baselines.json")
        parts += ["## Baselines without evidence",
                  table(["Baseline", "Accuracy [95% CI]", "Macro-F1 [95% CI]"],
                        [[n, ci(m["accuracy"]), ci(m["macro_f1"])] for n, m in b.items()])]

    # every pipeline_*.json is one system (main run, zero-shot NLI, LLM judge, other seeds...)
    runs = {p.stem.replace("pipeline", "").strip("_") or "main": load_json(p) for p in sorted(res.glob("pipeline*.json"))}
    if runs:
        parts += ["## End-to-end systems", table(head, [pipeline_row(f"{n} ({r['verifier']})", r["main"]) for n, r in runs.items()])]
        # the seed runs all use temperature 1, so they are comparable with each other
        seeds = [r["main"]["macro_f1"]["value"] for n, r in runs.items() if n.startswith("seed")]
        if len(seeds) > 1:
            parts.append(f"Macro-F1 over {len(seeds)} seeds: {np.mean(seeds):.3f} ± {np.std(seeds):.3f}")
    if "main" in runs:
        p = runs["main"]
        parts += ["## A2 Reranker", table(head, [pipeline_row("with reranker", p["main"]), pipeline_row("without reranker", p["A2_no_reranker"])])]
        parts += ["## A3 Number of evidence passages", table(head, [pipeline_row(f"k={m['k']}", m) for m in p["A3_number_of_evidence"]])]
        parts += ["## A4 Aggregation", table(head, [pipeline_row(m["aggregation"], m) for m in p["A4_aggregation"]])]
        parts += ["## A6 Oracle evidence", table(head, [pipeline_row("retrieved evidence", p["main"]), pipeline_row("gold evidence", p["A6_oracle_evidence"])])]
        e = p["errors_fixed_by_oracle"]
        parts.append(f"{e['fixed']} of the {e['n_errors']} errors ({e['share']:.0%}) disappear with gold evidence, so they come from retrieval.")
        parts += ["McNemar tests:", table(["Comparison", "b", "c", "p-value"], [[n, t["b"], t["c"], f"{t['p_value']:.4f}"] for n, t in p["mcnemar"].items()])]
        parts.append(f"Latency per claim: p50 {p['latency_ms_per_claim']['p50']:.0f} ms, p95 {p['latency_ms_per_claim']['p95']:.0f} ms")
        parts += ["Per-class results (main system):", table(["Class", "Precision", "Recall", "F1", "Support"],
                  [[c, f"{m['precision']:.3f}", f"{m['recall']:.3f}", f"{m['f1']:.3f}", m["support"]] for c, m in p["main"]["per_class"].items()])]

    if (res / "calibration.json").exists():
        c = load_json(res / "calibration.json")
        parts += [f"## Calibration (T = {c['temperature']:.3f}, threshold = {c['threshold']})",
                  table(["", "ECE", "AURC"], [[n, f"{c[n]['ece']:.4f}", f"{c[n]['aurc']:.4f}"] for n in ("before", "after")])]
        rows = [[a["threshold"], a["n_alerts"], f"{a['alert_precision']:.3f}", f"{a['alert_recall']:.3f}", f"{s['coverage']:.3f}", f"{s['selective_accuracy']:.3f}"]
                for a, s in zip(c["after"]["alerts"], c["after"]["selective"])]
        parts += ["Abstention (after temperature scaling):",
                  table(["Threshold", "Alerts", "Alert precision", "Alert recall", "Coverage", "Selective accuracy"], rows)]

    given = sorted(res.glob("given_*.json"))
    if given:
        rows = []
        for path in given:
            g = load_json(path)
            rows.append([path.stem.replace("given_", ""), g["verifier"], g["n"], ci(g["accuracy"]), ci(g["macro_f1"]), f"{g['ece']:.3f}"])
        parts += ["## Verifier-only test sets", table(["Run", "Verifier", "n", "Accuracy [95% CI]", "Macro-F1 [95% CI]", "ECE"], rows)]
        for path in given:
            g = load_json(path)
            for key in ("by_category", "by_perturbation"):
                if key in g:
                    parts += [f"{path.stem} — {key.replace('_', ' ')}:",
                              table(["Group", "n", "Accuracy", "Not-SUPPORTED rate"],
                                    [[n, m["n"], f"{m['accuracy']:.3f}", f"{m['not_supported_rate']:.3f}"] for n, m in g[key].items()])]
            if "consistency" in g:
                parts.append(f"{path.stem}: originals predicted SUPPORTED {g['originals_supported_rate']:.3f}, consistency {g['consistency']:.3f}")

    aggre = sorted(res.glob("aggrefact*.json"))
    if aggre:
        runs_a = {p.stem: load_json(p) for p in aggre}
        names = sorted({n for r in runs_a.values() for n in r["by_dataset"]})
        rows = [[f"{stem} ({r['verifier']})"] + [f"{r['by_dataset'][n]['balanced_accuracy']:.3f}" if n in r["by_dataset"] else "" for n in names]
                + [f"{r['mean_balanced_accuracy']:.3f}"] for stem, r in runs_a.items()]
        parts += ["## LLM-AggreFact (balanced accuracy, subsample)", table(["Run"] + names + ["Mean"], rows)]

    if (res / "efficiency.json").exists():
        e = load_json(res / "efficiency.json")
        names = [n for n in ("fp32_cpu", "int8_cpu", "int8_ffn_cpu") if n in e]
        rows = [[n, f"{e[n]['size_mb']:.0f}", f"{e[n]['latency_5_pairs']['p50_ms']:.0f}", f"{e[n]['latency_5_pairs']['p95_ms']:.0f}",
                 f"{e[n]['seconds_per_1000_claims']:.0f}", f"{e[n]['accuracy_gold_evidence']:.3f}",
                 f"{e[n].get('macro_f1_sr_gold_evidence', float('nan')):.3f}"] for n in names]
        parts += [f"## Efficiency ({e['n_parameters'] / 1e6:.0f}M parameters, CPU)",
                  table(["Model", "Size (MB)", "p50 ms / claim", "p95 ms / claim", "Seconds / 1,000 claims",
                         "Accuracy (gold evidence)", "Macro-F1 S/R (gold evidence)"], rows)]

    if (res / "sweep.json").exists():
        sweep = load_json(res / "sweep.json")
        keys = [k for k in sweep[0] if k != "dev_macro_f1"]
        parts += ["## Hyperparameter search (dev set)",
                  table(keys + ["Dev macro-F1"], [[r[k] for k in keys] + [f"{r['dev_macro_f1']:.4f}"] for r in sorted(sweep, key=lambda r: -r["dev_macro_f1"])])]

    out = res / "tables.md"
    out.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(parts) - 1} blocks)")


if __name__ == "__main__":
    main()
